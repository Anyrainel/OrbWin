import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const template = "internal/coldassets/compiled.go";
const script = "scripts/session-cold-payload-input.mjs";
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const roles = ["orbwin-services", "orbwin-trust"];
function payload(bytes) {
  assert.ok(
    bytes.length >= 64 && bytes.length <= 16 << 20,
    "Cold ELF size differs",
  );
  assert.ok(
    bytes.subarray(0, 7).equals(Buffer.from([0x7f, 69, 76, 70, 2, 1, 1])) &&
      bytes.readUInt16LE(18) === 62,
    "Cold ELF is not Linux amd64",
  );
  return { sha256: hash(bytes), size: bytes.length };
}
function generated(bytes) {
  return Buffer.from(
    "// Generated fixed cold SDK payloads; output-only Go overlay.\npackage coldassets\n\nfunc compiledPayloads() (Payloads, error) { return decodePayloads(" +
      bytes
        .map(
          (b) =>
            JSON.stringify(b.toString("base64")) +
            ", " +
            JSON.stringify(hash(b)),
        )
        .join(", ") +
      ") }\n",
  );
}
function proof(root, output) {
  const bytes = roles.map((name) => readFileSync(resolve(output, name)));
  const source = generated(bytes);
  return {
    manifest: {
      schema: 1,
      format: "compiled-base64-elf-v1",
      generatorSHA256: hash(readFileSync(resolve(root, script))),
      templateSHA256: hash(
        readFileSync(resolve(root, "backend-tools/session", template)),
      ),
      generatedSHA256: hash(source),
      payloads: Object.fromEntries(
        roles.map((name, n) => [name, payload(bytes[n])]),
      ),
    },
    source,
    overlay: {
      Replace: {
        [resolve(root, "backend-tools/session", template)]: resolve(
          output,
          ".cold-build-input/compiled.go",
        ),
      },
    },
  };
}

export function prepareColdPayloadInput(root, output) {
  const p = proof(root, output);
  const directory = resolve(output, ".cold-build-input");
  mkdirSync(directory); // CREATE_NEW; no live-source mutation or cleanup sweep.
  writeFileSync(resolve(directory, "compiled.go"), p.source, { flag: "wx" });
  writeFileSync(resolve(directory, "overlay.json"), JSON.stringify(p.overlay), {
    flag: "wx",
  });
  return {
    manifest: p.manifest,
    argument: "-overlay=" + resolve(directory, "overlay.json"),
  };
}

// A packaged artifact is relocated and has no build-only Go overlay. Recompute
// its complete payload/source provenance and verify the same embedded bytes;
// manifest paths never choose inputs.
function verifyArtifact(root, output, manifest) {
  const p = proof(root, output);
  assert.deepEqual(manifest, p.manifest, "Cold SDK payload provenance changed");
  const manager = readFileSync(resolve(output, "orbwin-session.exe"));
  for (const role of roles) {
    const bytes = readFileSync(resolve(output, role));
    assert.ok(
      manager.includes(Buffer.from(bytes.toString("base64"))) &&
        manager.includes(Buffer.from(hash(bytes))),
      "Cold payload was not linked into the SDK manager",
    );
  }
  return p;
}

export function verifyColdPayloadArtifact(root, output, manifest) {
  return verifyArtifact(root, output, manifest).manifest;
}

// Original SDK build inputs must additionally retain the exact generated source
// and absolute overlay mapping. Packaging must not weaken those build checks.
export function verifyColdPayloadInput(root, output, manifest) {
  const p = verifyArtifact(root, output, manifest);
  assert.ok(
    readFileSync(resolve(output, ".cold-build-input/compiled.go")).equals(
      p.source,
    ),
    "Cold SDK generated bytes changed",
  );
  assert.deepEqual(
    JSON.parse(readFileSync(resolve(output, ".cold-build-input/overlay.json"))),
    p.overlay,
    "Cold SDK overlay mapping changed",
  );
  return p.manifest;
}
